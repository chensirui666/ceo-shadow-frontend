async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  await page.goto('http://127.0.0.1:5192')
  await page.evaluate(() => {
    localStorage.setItem('friday-demo-session', JSON.stringify({ email: 'sirui.chen@stardust.ai', route: 'library' }))
    localStorage.setItem('friday-language', 'zh')
  })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.reload()
  const open = async (name) => { await page.getByRole('button', { name, exact: true }).click() }
  const frame = () => page.frameLocator('.library-document-frame')
  const menu = async (name) => { await page.getByRole('button', { name: `更多操作：${name}`, exact: true }).click() }
  await page.locator('.library-row').first().waitFor()
  check(await page.locator('.library-row').count() === 17, 'Sample files missing')
  check(await page.getByRole('searchbox').getAttribute('placeholder') === null, 'Search must have no placeholder')
  const searchStyle = await page.locator('.library-search').evaluate((element) => ({ background: getComputedStyle(element).backgroundColor, shadow: getComputedStyle(element).boxShadow }))
  check(searchStyle.background === 'rgb(255, 255, 255)' && searchStyle.shadow === 'none', 'Search must be white without a shadow')
  check(await page.locator('.library-format').first().innerText() === 'PDF', 'Actual format must be visible')
  check(/^\d{4}-\d{2}-\d{2}$/.test(await page.locator('.library-row time').first().innerText()), 'Date must include year, month and day')
  check(!/项目频道|客户交付群|原日程已删除/.test(await page.locator('.library-file-list').innerText()), 'Sources leaked into list')
  const dimensions = await page.evaluate(() => ({
    toolbar: [...document.querySelectorAll('.library-search,.library-filter [data-slot="select-trigger"]')].map((element) => ({ top: element.getBoundingClientRect().top, height: element.getBoundingClientRect().height })),
    widths: [...document.querySelectorAll('.library-format')].map((element) => element.getBoundingClientRect().width),
  }))
  check(dimensions.toolbar.every((item) => item.height === 38 && item.top === dimensions.toolbar[0].top), 'Toolbar controls must align')
  check(dimensions.widths.every((width) => width === 60), 'Format chips must have one fixed width')
  const headerTop = await page.locator('.library-header').evaluate((element) => element.getBoundingClientRect().top)
  await page.locator('.library-main').evaluate((element) => { element.scrollTop = 200 })
  check(await page.locator('.library-header').evaluate((element) => element.getBoundingClientRect().top) < headerTop - 100, 'Whole Library content must scroll')
  await page.locator('.library-main').evaluate((element) => { element.scrollTop = 0 })
  await page.getByRole('button', { name: '网格视图', exact: true }).click()
  check(await page.locator('.library-file-grid .library-row').count() === 17, 'Grid must show the same files')
  check(await page.locator('.library-file-grid img').count() === 0, 'Grid should use mock thumbnails')
  await page.getByRole('searchbox').fill('本周上线')
  check(await page.locator('.library-row').count() === 1, 'Grid search failed')
  await open('本周上线检查清单')
  await frame().getByRole('heading', { name: '本周上线检查清单', exact: true }).waitFor()
  await open('关闭预览')
  await menu('本周上线检查清单')
  await page.getByRole('menuitem', { name: '重命名', exact: true }).click()
  await page.getByRole('textbox', { name: '文件名称', exact: true }).fill('本周上线网格改名')
  await page.getByRole('textbox', { name: '文件名称', exact: true }).press('Enter')
  await page.getByRole('button', { name: '本周上线网格改名', exact: true }).waitFor()
  await menu('本周上线网格改名')
  await page.getByRole('menuitem', { name: '重命名', exact: true }).click()
  await page.getByRole('textbox', { name: '文件名称', exact: true }).fill('本周上线检查清单')
  await page.getByRole('textbox', { name: '文件名称', exact: true }).press('Enter')
  await page.getByRole('button', { name: '列表视图', exact: true }).click()
  check(await page.getByRole('searchbox').inputValue() === '本周上线', 'View switch lost search')
  await page.getByRole('searchbox').fill('')
  await page.getByRole('button', { name: /全部 类型/ }).click()
  await page.getByRole('option', { name: '文档', exact: true }).click()
  check(await page.locator('.library-row').count() === 5, 'Document category must include PDF, MD, DOCX, TXT, HTML')
  await page.getByRole('searchbox').fill('THIS DOES NOT EXIST')
  await page.getByText('没有找到符合条件的文件', { exact: true }).waitFor()
  await page.getByRole('button', { name: '清除筛选', exact: true }).first().click()
  check(await page.getByRole('searchbox').inputValue() === '', 'Clear must reset search')
  check(await page.locator('.library-row').count() === 17, 'Clear must restore all files')

  await open('本周上线检查清单')
  await frame().getByRole('heading', { name: '本周上线检查清单', exact: true }).waitFor()
  await open('项目工作记录')
  await frame().getByText('这是第二页完整内容，用于验证多页阅读。', { exact: true }).waitFor()
  check(await frame().locator('meta[http-equiv="Content-Security-Policy"]').count() === 1, 'DOCX cleared iframe policy')
  await open('上线检查汇报')
  await frame().getByText('检查清单', { exact: true }).waitFor()
  check(!(await page.frames().find((item) => item.url() === 'about:srcdoc').evaluate(() => document.body.scrollWidth > innerWidth + 1)), 'Slides overflow preview width')
  await open('交付资源与排期核对')
  await page.getByRole('rowheader', { name: '核对交付资源', exact: true }).waitFor()
  await page.getByRole('tab', { name: '说明', exact: true }).click()
  await page.getByRole('rowheader', { name: /这是 Library 的格式预览示例/ }).waitFor()
  await open('检查进度')
  await page.getByRole('gridcell', { name: '包含表格、图片和文档', exact: true }).waitFor()
  for (const [name, content] of [['工作记录', '第一项：查看文件原文。'], ['检查配置', '"demo": true'], ['Python 示例', 'def greeting(name):'], ['JavaScript 示例', 'const checks']]) {
    await open(name)
    await page.locator('.library-text-content').filter({ hasText: content }).waitFor()
  }
  for (const name of ['产品方案示意图', '方案图片', '方案图片 WebP', '动图示例', '矢量示意图']) {
    await open(name)
    await page.getByRole('img', { name, exact: true }).waitFor()
    await page.waitForFunction(() => { const img = document.querySelector('.library-image-content img'); return img?.complete && img.naturalWidth > 0 })
  }
  await open('项目页面')
  await frame().getByRole('heading', { name: '项目页面预览' }).waitFor()
  check(await page.locator('.library-document-frame').getAttribute('sandbox') === 'allow-same-origin', 'HTML scripts must be disabled')
  await open('资料压缩包')
  await page.getByText('此格式暂不支持预览，可下载原文件查看。', { exact: true }).waitFor()
  await open('项目周报')
  await page.locator('.library-document-frame[src^="blob:"]').waitFor()
  check((await page.locator('.library-document-frame').getAttribute('src')).includes('toolbar=0&navpanes=0&view=FitH'), 'PDF must fit the panel without its default sidebar')
  const pdfDownload = page.waitForEvent('download')
  await open('下载')
  const pdf = await pdfDownload
  check(pdf.suggestedFilename() === '项目周报.pdf', 'PDF download extension changed')
  await pdf.saveAs('/tmp/library-downloaded.pdf')

  await open('本周上线检查清单')
  await menu('本周上线检查清单')
  await page.getByRole('menuitem', { name: '重命名', exact: true }).click()
  await page.getByRole('textbox', { name: '文件名称', exact: true }).fill('改名示例')
  await page.getByRole('textbox', { name: '文件名称', exact: true }).press('Enter')
  await page.getByRole('heading', { name: '改名示例', exact: true }).waitFor()
  await frame().getByRole('heading', { name: '本周上线检查清单', exact: true }).waitFor()
  const renamedDownload = page.waitForEvent('download')
  await open('下载')
  check((await renamedDownload).suggestedFilename() === '改名示例.md', 'Rename changed actual format')
  await menu('改名示例')
  check(await page.getByRole('menuitem', { name: '删除', exact: true }).evaluate((element) => getComputedStyle(element).color) === 'rgb(178, 69, 72)', 'Available delete must be red')
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  await page.getByRole('dialog').locator('.modal-cancel').click()
  check(await page.getByRole('heading', { name: '改名示例', exact: true }).count() === 1, 'Cancel deleted preview')
  await menu('改名示例')
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '删除', exact: true }).click()
  await page.locator('.library-preview').waitFor({ state: 'detached' })
  check(await page.locator('.library-row').count() === 16, 'Delete did not remove file')
  await menu('项目工作记录')
  check(await page.getByRole('menuitem', { name: '删除', exact: true }).getAttribute('aria-disabled') === 'true', 'Sending file deletion must be disabled')
  await page.keyboard.press('Escape')
  await open('交付资源与排期核对')
  await page.locator('.library-source-details [data-slot="accordion-trigger"]').click()
  await open('客户交付群')
  await page.getByText('是否可以承诺本月完成交付？', { exact: true }).first().waitFor()
  await open('Library')
  await page.locator('.library-row').first().waitFor()
  check(await page.locator('.library-row').count() === 16, 'Navigation lost session mutations')
  await page.reload()
  await page.locator('.library-row').first().waitFor()
  check(await page.locator('.library-row').count() === 17, 'Reload should restore demo data')

  await page.route('**/library-samples/checklist.md', (route) => route.fulfill({ status: 403, body: 'Forbidden' }))
  await open('本周上线检查清单')
  await page.getByText('你没有权限查看此文件。', { exact: true }).waitFor()
  check(await page.locator('.library-document-frame').count() === 0, 'Forbidden file exposed content')
  await page.unroute('**/library-samples/checklist.md')
  await open('重试')
  await frame().getByRole('heading', { name: '本周上线检查清单', exact: true }).waitFor()
  await page.screenshot({ path: '/tmp/library-verified.png' })
  await page.route('**/library-samples/notes.txt', (route) => route.fulfill({ status: 404, body: 'Missing' }))
  await open('工作记录')
  await page.getByText('文件不存在或已被删除，列表已更新。', { exact: true }).waitFor()
  check(await page.locator('.library-preview').count() === 0, 'Missing file preview remained open')
  check(await page.locator('.library-row').count() === 16, 'Missing file metadata remained in list')
  await page.unroute('**/library-samples/notes.txt')
  await page.evaluate(() => { window.libraryScriptExecuted = false })
  await page.route('**/library-samples/report.html', (route) => route.fulfill({ status: 200, contentType: 'text/html', body: '<h1>Safe document content</h1><script>parent.libraryScriptExecuted=true</script><img src="invalid" onerror="parent.libraryScriptExecuted=true">' }))
  await open('项目页面')
  await frame().getByRole('heading', { name: 'Safe document content' }).waitFor()
  check(await page.evaluate(() => window.libraryScriptExecuted) === false, 'Document script escaped preview')
  await page.unroute('**/library-samples/report.html')
  return 'Passed: 16 previews and ZIP fallback, filters, inline rename, delete/cancel, disabled delete, actual downloads, Message source, session reset, 403/404 and HTML isolation.'
}
